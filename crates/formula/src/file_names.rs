/// The prefix files put before a function's name, in any letter case and without a prefix of its
/// own: `_xlfn.` for `XLOOKUP`, `_xlfn._xlws.` for `FILTER`, none for `SUM`. Excel reads a call
/// without its prefix as a call of a workbook name of that spelling, when there is one (Batch 5,
/// `x30-lambda-collisions`).
pub fn file_prefix(name: &str) -> Option<&'static str> {
    FUTURE_FUNCTIONS.iter().find_map(|f| match f.strip_prefix("_xlws.") {
        Some(ws) => ws.eq_ignore_ascii_case(name).then_some("_xlfn._xlws."),
        None => f.eq_ignore_ascii_case(name).then_some("_xlfn."),
    })
}

const UDF_PREFIX: &str = "_xludf.";

/// The name a `_xludf.` call calls (`_xludf.VStack` → `VStack`, any letter case): a user-defined
/// function or workbook name, never the built-in of the same name.
pub fn user_defined_name(name: &str) -> Option<&str> {
    name.get(..UDF_PREFIX.len()).filter(|p| p.eq_ignore_ascii_case(UDF_PREFIX)).and_then(|_| name.get(UDF_PREFIX.len()..))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn prefixes() {
        assert_eq!(file_prefix("xlookup"), Some("_xlfn."));
        assert_eq!(file_prefix("Filter"), Some("_xlfn._xlws."));
        assert_eq!(file_prefix("NETWORKDAYS.INTL"), None);
        assert_eq!(file_prefix("_xlfn.XLOOKUP"), None);
        assert_eq!(user_defined_name("_XLUDF.VStack"), Some("VStack"));
        assert_eq!(user_defined_name("VSTACK"), None);
        assert_eq!(user_defined_name("_xlud"), None);
    }
}
